var themeIdx = 0

func themeNames() []string {
	var n []string
	for _, t := range themes {
		n = append(n, t.Name)
	}
	return n
}

// setTheme switches the colours (i is an index into themes) and repaints.
func (a *App) setTheme(i int) {
	if i < 0 || i >= len(themes) {
		return
	}
	themeIdx = i
	paletteRGB = themes[i].C
	if r, ok := a.be.(interface{ Repaint() }); ok {
		r.Repaint()
	}
}

// pickTheme shows a list; moving onto a theme is not previewed, Enter applies it.
func (a *App) pickTheme() {
	var items []PItem
	for i, t := range themes {
		i, t := i, t
		d := ""
		if i == themeIdx {
			d = "current"
		}
		items = append(items, PItem{Label: t.Name, Detail: d, Run: func(a *App) {
			a.setTheme(i)
			a.saveSettings()
			a.say("Theme: " + t.Name)
		}})
	}
	a.pick("Select Color Theme", items)
}
